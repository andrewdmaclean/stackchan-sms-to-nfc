// Runs the upstream browser WebAssembly MOD builder; no native firmware toolchain.
// Uses the complete, pinned local community checkout.
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const QRCode = require('qrcode');
const prepareGallery = require('./add-to-gallery.cjs');
const buildCam2QR = require('./build-cam2qr.cjs');

// Module names recorded in an XS archive: each is a size-prefixed PATH chunk.
function archiveModules(bytes) {
  const buffer = Buffer.from(bytes), names = [];
  for (let at = buffer.indexOf('PATH'); at !== -1; at = buffer.indexOf('PATH', at + 4))
    names.push(buffer.subarray(at + 4, at - 4 + buffer.readUInt32BE(at - 4)).toString('latin1').replace(/\0+$/, ''));
  return names;
}

(async () => {
  const root = path.resolve(__dirname, '..');
  const checkout = path.join(root, 'upstream/stack-chan');
  const revision = '6a8f7553610e5d91770901e76fd93a0c50cfd970';
  if (!fs.existsSync(path.join(checkout, '.git'))) throw new Error('The StackChan tools are missing. Run npm run setup first.');
  const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: checkout, encoding: 'utf8' }).trim();
  if (head !== revision) throw new Error(`Expected community v2.0.1 (${revision}); found ${head}.`);
  const editor = path.join(checkout, 'web/editor');
  const { default: createTools } = await import(pathToFileURL(path.join(editor, 'vendor/tools.js')));
  const { buildModArchive, xsArchiveVersion } = await import(pathToFileURL(path.join(editor, 'mod-builder.mjs')));
  const dir = path.join(root, 'robot');
  buildCam2QR(path.join(dir, 'vendor'));
  if (!fs.existsSync(path.join(dir, 'config.js'))) throw new Error('robot/config.js is missing. Run npm run deploy -- +1YOURNUMBER first.');
  const eventConfig = (await import(pathToFileURL(path.join(dir, 'config.js')))).default;
  // The "text me" QR shown on the robot's screen: SMSTO opens a text to the number on iOS and Android.
  const smsQR = eventConfig.smsNumber && QRCode.create(`SMSTO:${eventConfig.smsNumber}:`, { errorCorrectionLevel: 'M' }).modules;
  fs.writeFileSync(path.join(dir, 'text-me-qr.js'), '// Generated by scripts/build-robot.cjs from config.smsNumber. Do not edit.\n' +
    'export default ' + (smsQR ? JSON.stringify({ size: smsQR.size, rows: Array.from({ length: smsQR.size }, (_, y) =>
      Array.from({ length: smsQR.size }, (_, x) => smsQR.get(y, x) ? '1' : '0').join('')) }) : 'undefined') + '\n');
  if (smsQR) console.log(`Text-me QR: SMSTO:${eventConfig.smsNumber}: (${smsQR.size}x${smsQR.size})`);
  const output = path.join(root, '.artifacts');
  fs.mkdirSync(output, { recursive: true });
  const results = [];
  {
    const kind = 'sms-to-nfc';
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
    delete manifest.include; // Browser mcrun supplies the MOD base; no SDK tree is needed.
    // Supply exactly the manifest's modules. mcrun silently skips a missing file, and the host then falls back
    // to its default app because the MOD cannot import it.
    const modules = Object.entries(manifest.modules).flatMap(([name, source]) =>
      name === '*' ? source.map(file => [file.replace(/^\.\//, ''), file]) : [[name, source]]);
    const names = modules.filter(([name]) => name !== 'mod').map(([, source]) => source.replace(/^\.\//, '') + '.js');
    for (const name of names) if (!fs.existsSync(path.join(dir, name))) throw new Error(`MOD source missing: ${name}`);
    const bytes = await buildModArchive(createTools, {
      modJs: fs.readFileSync(path.join(dir, 'mod.js'), 'utf8'),
      manifest, name: kind,
      files: names.map(name => ({ path: name, bytes: new Uint8Array(fs.readFileSync(path.join(dir, name))) })),
    });
    const missing = modules.map(([name]) => name).filter(name => !archiveModules(bytes).includes(name));
    if (missing.length) throw new Error(`${kind} archive is missing modules: ${missing.join(', ')}`);
    const archive = path.join(output, kind + '.xsa');
    fs.writeFileSync(archive, bytes, { mode: 0o600 });
    results.push({ name: kind, archive_bytes: bytes.length, xs_version: xsArchiveVersion(bytes),
      sha256: crypto.createHash('sha256').update(bytes).digest('hex'), uses_native_extension: false,
      requires_configuration: true, hardware_tested: false });
    console.log(`${kind}: ${bytes.length} bytes, XS ${xsArchiveVersion(bytes).join('.')}`);
  }
  fs.writeFileSync(path.join(output, 'qr-mod-build.json'), JSON.stringify({
    community_commit: revision,
    builder: 'upstream browser WebAssembly MOD builder', results,
  }, null, 2));
  prepareGallery({ checkout, source: dir, output, eventConfig });
  console.log('Built .artifacts/sms-to-nfc.xsa. Install it from http://127.0.0.1:5173/mod-gallery/?mod=local.stackchan.sms-to-nfc (npm start).');
})().catch(error => { console.error(error.message); process.exitCode = 1; });
