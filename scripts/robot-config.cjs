// Point the event MOD's ignored config.js at the deployed Twilio backend (backend/deploy.sh).
// Keeps the station and the optional robot settings already in config.js. Never prints the device token.
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = path.resolve(__dirname, '..');
const deploy = path.join(root, '.deploy/event');
const configFile = path.join(root, 'robot/config.js');
const marker = '// Generated by scripts/robot-config.cjs; contains the Twilio device token. Keep private.';
const generated = [marker, '// Generated by scripts/event-cloud-config.cjs; contains the Twilio device token. Keep private.'];
(async () => {
  if (!fs.existsSync(path.join(deploy, 'service.json'))) throw new Error('Run npm run deploy -- +1YOURNUMBER first.');
  const service = JSON.parse(fs.readFileSync(path.join(deploy, 'service.json'), 'utf8'));
  const token = fs.readFileSync(path.join(deploy, '.env'), 'utf8').match(/^EVENT_DEVICE_TOKEN=(.+)$/m)?.[1];
  if (!token) throw new Error('EVENT_DEVICE_TOKEN is missing from .deploy/event/.env; rerun npm run deploy.');
  let current = {};
  if (fs.existsSync(configFile)) {
    if (!generated.some(line => fs.readFileSync(configFile, 'utf8').startsWith(line)))
      throw new Error('Existing MOD config.js was not generated by a script; preserve it and edit it by hand.');
    current = (await import(pathToFileURL(configFile).href + '?' + Date.now())).default;
  }
  const flags = Object.fromEntries(['enableNFCWrite', 'motion', 'napAfterSeconds', 'scanTimeoutSeconds']
    .filter(key => key in current).map(key => [key, current[key]]));
  fs.writeFileSync(configFile, marker + '\nexport default ' + JSON.stringify({
    host: service.domain, port: 443, secure: true, token, station: current.station || 'stackchan-01', ...flags,
    // Shown on the robot's screen as a QR that opens a text to this number.
    smsNumber: service.phone,
  }, null, 2) + '\n', { mode: 0o600 });
  console.log(`Robot configured for https://${service.domain} (robot/config.js). Next: npm run build`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
